"""Score prepared pre-pitch contexts with a saved baseline experiment."""

import argparse
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from xgboost import XGBRegressor, XGBClassifier

from train_model import CATEGORICAL, CONTEXT, FEATURES, NUMERIC
from model_policy import scoring_model


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, required=True, help="Saved artifact directory")
    parser.add_argument("--input", type=Path, required=True, help="CSV containing prepared feature columns")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    report = json.loads((args.run / "metrics.json").read_text())
    frame = pd.read_csv(args.input, dtype={col: str for col in CATEGORICAL})
    features = report["features"]
    missing = set(features) - set(frame)
    if missing:
        parser.error(f"Missing feature columns: {sorted(missing)}")
    if frame.empty:
        parser.error("Input contains no contexts")
    for col in set(features) - set(CATEGORICAL):
        frame[col] = pd.to_numeric(frame[col], errors="raise")
    for col in CATEGORICAL:
        frame[col] = frame[col].fillna("UNKNOWN").astype(str)
    # The local encoder is part of the artifact generated by train_model.py.
    encoder = joblib.load(args.run / "encoder.joblib")
    whiff = report.get("task") == "whiff"
    model = XGBClassifier() if whiff else XGBRegressor()
    model.load_model(args.run / "xgboost.ubj")
    encoded = encoder.transform(frame[features])
    frame["predicted_xgboost"] = model.predict_proba(encoded)[:, 1] if whiff else model.predict(encoded)
    selected = report.get("scoring_model")
    if selected is None:
        interval_name = "log_loss_improvement_95_percent_interval" if whiff else "rmse_improvement_95_percent_interval"
        selected = scoring_model(report["metrics"], report["selected_on_validation"],
            report["test_uncertainty"][interval_name], "log_loss" if whiff else "rmse")
    if selected == "training_mean":
        estimate = np.full(len(frame), report["training_target_mean"])
    elif selected == "shrunk_context_mean":
        context = pd.read_csv(args.run / "context_baseline.csv")
        mean = report["training_target_mean"]
        context["estimate"] = (context["sum"] + 20 * mean) / (context["count"] + 20)
        estimate = frame[CONTEXT].merge(context[CONTEXT + ["estimate"]], on=CONTEXT,
                                       how="left", sort=False)["estimate"].fillna(mean).to_numpy()
    else:
        estimate = frame["predicted_xgboost"].to_numpy()
    frame["predicted_score"] = estimate
    frame["scoring_model"] = selected
    frame["validation_selected_model"] = report["selected_on_validation"]
    frame["interpretation"] = "whiff probability per pitch" if whiff else "exploratory batting run-expectancy delta; lower favors pitcher"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(args.output, index=False)
    print(f"Scored {len(frame)} contexts -> {args.output}")


if __name__ == "__main__":
    main()
